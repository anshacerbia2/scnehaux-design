// Copies the tokens of @scnx/system into this repository, byte for byte, from the
// package's own emitter at one pinned ui-platform commit (ADR-UIP-VIS-002 item 1:
// "the package wins and the reference is regenerated").
//
//   npm ci
//   node scripts/sync-tokens.mjs [--check]
//
// scripts/sync-tokens.json names the repository, the commit, and the themes. The run
// downloads that commit's source, runs packages/design-system/scripts/tokens/emit.mjs,
// and writes the files a page needs at their published paths under `out`:
// tokens/css/<theme>.css, tokens/json/<theme>.json, and fonts/. The layout matches the
// package's dist/, so the CSS's relative font URLs resolve unchanged, and a page moves
// to the published package by changing only the path prefix. SOURCE.json records the
// commit and a SHA-256 of every file. The emitter's three dependencies are pinned in
// package.json to the versions in that commit's pnpm-lock.yaml; the run stops if they
// differ, because a different Sass can emit different bytes. With --check nothing is
// written; the run fails if the committed files differ from a fresh emission.
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const config = JSON.parse(fs.readFileSync(path.join(ROOT, "scripts", "sync-tokens.json"), "utf8"));
const check = process.argv.includes("--check");
const EMITTER_DEPS = ["sass", "colorjs.io", "css-tree"];

// The source lives under .cache/ inside the repository so that the emitter's bare
// imports resolve to this repository's node_modules.
const cache = path.join(ROOT, ".cache", "sync-tokens", config.commit);
const archive = `${cache}.tar.gz`;
if (!fs.existsSync(path.join(cache, config.package, "package.json"))) {
  fs.mkdirSync(cache, { recursive: true });
  const url = `https://codeload.github.com/${config.repository}/tar.gz/${config.commit}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  fs.writeFileSync(archive, Buffer.from(await res.arrayBuffer()));
  const top = `${config.repository.split("/")[1]}-${config.commit}`;
  // Only the package and the shared scripts it imports; the rest of the monorepo is not needed.
  execFileSync("tar", ["-xzf", archive, "-C", cache, "--strip-components=1", `${top}/${config.package}`, `${top}/scripts`, `${top}/pnpm-lock.yaml`]);
  fs.rmSync(archive);
}

const lock = fs.readFileSync(path.join(cache, "pnpm-lock.yaml"), "utf8");
const mismatched = EMITTER_DEPS.filter((name) => {
  const locked = new RegExp(`^  ${name.replace(".", "\\.")}@([^:(]+):`, "m").exec(lock)?.[1];
  // Read the manifest by path: some of these packages do not export ./package.json.
  const installed = JSON.parse(fs.readFileSync(path.join(ROOT, "node_modules", name, "package.json"), "utf8")).version;
  if (locked !== installed) console.error(`${name}: ui-platform locks ${locked}, this repository has ${installed}`);
  return locked !== installed;
});
if (mismatched.length > 0) throw new Error("Pin the emitter's dependencies in package.json to the commit's pnpm-lock.yaml.");

const emitted = path.join(cache, "emitted");
fs.rmSync(emitted, { recursive: true, force: true });
execFileSync(process.execPath, ["scripts/tokens/emit.mjs", "--out", emitted], { cwd: path.join(cache, config.package), stdio: ["ignore", "ignore", "inherit"] });

const files = [
  ...config.themes.flatMap((theme) => [`tokens/css/${theme}.css`, `tokens/json/${theme}.json`]),
  ...fs.readdirSync(path.join(emitted, "fonts")).sort().map((name) => `fonts/${name}`),
];
const pkg = JSON.parse(fs.readFileSync(path.join(cache, config.package, "package.json"), "utf8"));
const sha256 = (buffer) => createHash("sha256").update(buffer).digest("hex");
const source = {
  package: pkg.name,
  version: pkg.version,
  repository: config.repository,
  commit: config.commit,
  emitter: `${config.package}/scripts/tokens/emit.mjs`,
  note: "Generated by scripts/sync-tokens.mjs. Do not edit; change scripts/sync-tokens.json and run it again.",
  files: Object.fromEntries(files.map((file) => [file, sha256(fs.readFileSync(path.join(emitted, file)))])),
};
const out = path.join(ROOT, config.out);
const sourceJson = `${JSON.stringify(source, null, 2)}\n`;

if (check) {
  const committed = (file) => (fs.existsSync(path.join(out, file)) ? fs.readFileSync(path.join(out, file)) : null);
  const stale = files.filter((file) => !committed(file)?.equals(fs.readFileSync(path.join(emitted, file))));
  if (committed("SOURCE.json")?.toString() !== sourceJson) stale.push("SOURCE.json");
  if (stale.length > 0) {
    console.error(`Out of date with ${config.repository}@${config.commit.slice(0, 7)}:\n  ${stale.join("\n  ")}`);
    process.exit(1);
  }
  console.log(`${files.length} files match ${config.repository}@${config.commit.slice(0, 7)}.`);
} else {
  fs.rmSync(out, { recursive: true, force: true });
  for (const file of files) {
    fs.mkdirSync(path.dirname(path.join(out, file)), { recursive: true });
    fs.copyFileSync(path.join(emitted, file), path.join(out, file));
  }
  fs.writeFileSync(path.join(out, "SOURCE.json"), sourceJson);
  console.log(`Wrote ${files.length} files from ${config.repository}@${config.commit.slice(0, 7)} to ${config.out}.`);
}
